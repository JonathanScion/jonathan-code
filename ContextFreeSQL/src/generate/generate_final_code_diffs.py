def generate_source_sql_for_tables(sql_buffer):
    """PostgreSQL: fill tmp_source_sql with the statements that would make the SOURCE (script side) table match the
    TARGET database - the reverse of what the script runs. Built from the state tables' stats (1 = only in script,
    2 = only in DB, 3 = different) plus the target's catalogs for its definitions. Tables that exist on one side only
    are handled per table in the page loop (DROP TABLE / the target's CREATE TABLE).
    ord mirrors the script's own order: drop FKs, indexes, check constraints; columns; add check constraints, indexes, FKs."""
    w = sql_buffer.write
    tbl_ok = "(T.tableStat NOT IN (1, 2) OR T.tableStat IS NULL)"
    w("\t\t-- Statements that would make the source (script side) match this database: the reverse of what the script runs\n")
    w("\t\tDROP TABLE IF EXISTS tmp_source_sql;\n")
    w("\t\tCREATE TEMP TABLE tmp_source_sql (ent_schema character varying (128), ent_name character varying (128), ord int, sub_ord text, sql_text text);\n")
    # FKs: drop the script's (only in script, or different)
    w("\t\tINSERT INTO tmp_source_sql\n")
    w("\t\tSELECT FK.fkey_table_schema, FK.fkey_table_name, 10, FK.fk_name,\n")
    w("\t\t\t'ALTER TABLE ' || FK.fkey_table_schema || '.' || FK.fkey_table_name || ' DROP CONSTRAINT ' || FK.fk_name || ';'\n")
    w("\t\tFROM ScriptFKs FK INNER JOIN ScriptTables T ON LOWER(FK.fkey_table_schema) = LOWER(T.table_schema) AND LOWER(FK.fkey_table_name) = LOWER(T.table_name)\n")
    w(f"\t\tWHERE FK.fkStat IN (1, 3) AND {tbl_ok};\n")
    # Indexes: drop the script's
    w("\t\tINSERT INTO tmp_source_sql\n")
    w("\t\tSELECT I.table_schema, I.table_name, 20, I.index_name,\n")
    w("\t\t\tCASE WHEN I.is_primary_key OR I.is_unique_constraint\n")
    w("\t\t\t\tTHEN 'ALTER TABLE ' || I.table_schema || '.' || I.table_name || ' DROP CONSTRAINT ' || I.index_name || ';'\n")
    w("\t\t\t\tELSE 'DROP INDEX ' || I.table_schema || '.' || I.index_name || ';' END\n")
    w("\t\tFROM ScriptIndexes I INNER JOIN ScriptTables T ON LOWER(I.table_schema) = LOWER(T.table_schema) AND LOWER(I.table_name) = LOWER(T.table_name)\n")
    w(f"\t\tWHERE I.indexStat IN (1, 3) AND {tbl_ok};\n")
    # Check constraints: drop the script's
    w("\t\tINSERT INTO tmp_source_sql\n")
    w("\t\tSELECT CC.table_schema, CC.table_name, 30, CC.constraint_name,\n")
    w("\t\t\t'ALTER TABLE ' || CC.table_schema || '.' || CC.table_name || ' DROP CONSTRAINT ' || CC.constraint_name || ';'\n")
    w("\t\tFROM ScriptCheckConstraints CC INNER JOIN ScriptTables T ON LOWER(CC.table_schema) = LOWER(T.table_schema) AND LOWER(CC.table_name) = LOWER(T.table_name)\n")
    w(f"\t\tWHERE CC.ccStat IN (1, 3) AND {tbl_ok};\n")
    # Columns: drop the script-only ones, add/alter to the target's definition
    w("\t\tINSERT INTO tmp_source_sql\n")
    w("\t\tSELECT C.table_schema, C.table_name, 40, C.col_name,\n")
    w("\t\t\tCASE C.colStat\n")
    w("\t\t\t\tWHEN 1 THEN 'ALTER TABLE ' || C.table_schema || '.' || C.table_name || ' DROP COLUMN ' || C.col_name || ';'\n")
    # An integer column defaulting to nextval() is added as serial, which creates its sequence - the sequence
    # the target's DEFAULT names may not exist on the source (same rule as the script side's _is_serial_default)
    serial_type = ("CASE WHEN pg_get_expr(d.adbin, d.adrelid) ILIKE 'nextval(%' THEN "
                   "CASE a.atttypid WHEN 'int4'::regtype THEN 'serial' WHEN 'int8'::regtype THEN 'bigserial' WHEN 'int2'::regtype THEN 'smallserial' END END")
    w(f"\t\t\t\tWHEN 2 THEN 'ALTER TABLE ' || C.table_schema || '.' || C.table_name || ' ADD COLUMN ' || C.col_name || ' ' || COALESCE({serial_type}, format_type(a.atttypid, a.atttypmod))\n")
    w("\t\t\t\t\t|| CASE a.attidentity WHEN 'a' THEN ' GENERATED ALWAYS AS IDENTITY' WHEN 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY' ELSE '' END\n")
    w("\t\t\t\t\t|| CASE WHEN a.attgenerated = 's' THEN ' GENERATED ALWAYS AS (' || pg_get_expr(d.adbin, d.adrelid) || ') STORED'\n")
    w(f"\t\t\t\t\t\tWHEN d.adbin IS NOT NULL AND {serial_type} IS NULL THEN ' DEFAULT ' || pg_get_expr(d.adbin, d.adrelid) ELSE '' END\n")
    w("\t\t\t\t\t|| CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE ' NULL' END || ';'\n")
    w("\t\t\t\tWHEN 3 THEN 'ALTER TABLE ' || C.table_schema || '.' || C.table_name || ' ALTER COLUMN ' || C.col_name || ' TYPE ' || format_type(a.atttypid, a.atttypmod)\n")
    w("\t\t\t\t\t|| E',\\n\\tALTER COLUMN ' || C.col_name || CASE WHEN a.attnotnull THEN ' SET NOT NULL' ELSE ' DROP NOT NULL' END || ';'\n")
    w("\t\t\t\t\t|| CASE WHEN C.is_identity_diff = B'1' THEN\n")
    w("\t\t\t\t\t\tE'\\nALTER TABLE ' || C.table_schema || '.' || C.table_name || ' ALTER COLUMN ' || C.col_name ||\n")
    w("\t\t\t\t\t\tCASE a.attidentity WHEN 'a' THEN ' ADD GENERATED ALWAYS AS IDENTITY;' WHEN 'd' THEN ' ADD GENERATED BY DEFAULT AS IDENTITY;' ELSE ' DROP IDENTITY IF EXISTS;' END\n")
    w("\t\t\t\t\tELSE '' END\n")
    w("\t\t\tEND\n")
    w("\t\tFROM ScriptCols C INNER JOIN ScriptTables T ON LOWER(C.table_schema) = LOWER(T.table_schema) AND LOWER(C.table_name) = LOWER(T.table_name)\n")
    w("\t\tLEFT JOIN pg_namespace n ON n.nspname = C.table_schema\n")
    w("\t\tLEFT JOIN pg_class cl ON cl.relnamespace = n.oid AND cl.relname = C.table_name AND cl.relkind IN ('r', 'p')\n")
    w("\t\tLEFT JOIN pg_attribute a ON a.attrelid = cl.oid AND a.attname = C.col_name AND a.attnum > 0 AND NOT a.attisdropped\n")
    w("\t\tLEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum\n")
    w(f"\t\tWHERE (C.colStat = 1 OR (C.colStat IN (2, 3) AND a.attnum IS NOT NULL)) AND {tbl_ok};\n")
    # Check constraints: add the target's
    w("\t\tINSERT INTO tmp_source_sql\n")
    w("\t\tSELECT CC.table_schema, CC.table_name, 70, CC.constraint_name,\n")
    w("\t\t\t'ALTER TABLE ' || CC.table_schema || '.' || CC.table_name || ' ADD CONSTRAINT ' || CC.constraint_name || ' ' || pg_get_constraintdef(con.oid) || ';'\n")
    w("\t\tFROM ScriptCheckConstraints CC INNER JOIN ScriptTables T ON LOWER(CC.table_schema) = LOWER(T.table_schema) AND LOWER(CC.table_name) = LOWER(T.table_name)\n")
    w("\t\tINNER JOIN pg_namespace n ON n.nspname = CC.table_schema\n")
    w("\t\tINNER JOIN pg_class cl ON cl.relnamespace = n.oid AND cl.relname = CC.table_name\n")
    w("\t\tINNER JOIN pg_constraint con ON con.conrelid = cl.oid AND con.conname = CC.constraint_name AND con.contype = 'c'\n")
    w(f"\t\tWHERE CC.ccStat IN (2, 3) AND {tbl_ok};\n")
    # Indexes: add the target's (as a constraint if it backs one)
    w("\t\tINSERT INTO tmp_source_sql\n")
    w("\t\tSELECT I.table_schema, I.table_name, 80, I.index_name,\n")
    w("\t\t\tCASE WHEN con.oid IS NOT NULL\n")
    w("\t\t\t\tTHEN 'ALTER TABLE ' || I.table_schema || '.' || I.table_name || ' ADD CONSTRAINT ' || I.index_name || ' ' || pg_get_constraintdef(con.oid) || ';'\n")
    w("\t\t\t\tELSE pg_get_indexdef(ic.oid) || ';' END\n")
    w("\t\tFROM ScriptIndexes I INNER JOIN ScriptTables T ON LOWER(I.table_schema) = LOWER(T.table_schema) AND LOWER(I.table_name) = LOWER(T.table_name)\n")
    w("\t\tINNER JOIN pg_namespace n ON n.nspname = I.table_schema\n")
    w("\t\tINNER JOIN pg_class ic ON ic.relnamespace = n.oid AND ic.relname = I.index_name AND ic.relkind IN ('i', 'I')\n")
    w("\t\tLEFT JOIN pg_constraint con ON con.conindid = ic.oid AND con.contype IN ('p', 'u', 'x')\n")
    w(f"\t\tWHERE I.indexStat IN (2, 3) AND {tbl_ok};\n")
    # FKs: add the target's
    w("\t\tINSERT INTO tmp_source_sql\n")
    w("\t\tSELECT FK.fkey_table_schema, FK.fkey_table_name, 90, FK.fk_name,\n")
    w("\t\t\t'ALTER TABLE ' || FK.fkey_table_schema || '.' || FK.fkey_table_name || ' ADD CONSTRAINT ' || FK.fk_name || ' ' || pg_get_constraintdef(con.oid) || ';'\n")
    w("\t\tFROM ScriptFKs FK INNER JOIN ScriptTables T ON LOWER(FK.fkey_table_schema) = LOWER(T.table_schema) AND LOWER(FK.fkey_table_name) = LOWER(T.table_name)\n")
    w("\t\tINNER JOIN pg_namespace n ON n.nspname = FK.fkey_table_schema\n")
    w("\t\tINNER JOIN pg_class cl ON cl.relnamespace = n.oid AND cl.relname = FK.fkey_table_name\n")
    w("\t\tINNER JOIN pg_constraint con ON con.conrelid = cl.oid AND con.conname = FK.fk_name AND con.contype = 'f'\n")
    w(f"\t\tWHERE FK.fkStat IN (2, 3) AND {tbl_ok};\n")
    w("\t\t\n")


def generate_code_diffs(db_type: DBType, sql_buffer, input_output: InputOutput, drops_extra_tables: bool = False, source_db_label: str = "", include_coded: bool = True):
    """Generate HTML diff files for coded entities with differences (codeStat=3), and for tables that are
    different or exist on one side only (tableStat 1,2,3). Table pages also list, side by side, the SQL statements
    that make each side match the other: for the target, what the script runs (from scriptoutput, tagged by
    ent_schema/ent_name); for the source, the reverse (see generate_source_sql_for_tables)"""
    left_title_sql, right_title_sql = utils.pg_panel_title_exprs(source_db_label)

    sql_buffer.write("\n")

    if db_type == DBType.PostgreSQL:
        sql_buffer.write("IF (htmlReport = True) THEN\n")
        sql_buffer.write("\tDECLARE \n")
        sql_buffer.write("\t\tdiff_template text;\n")
        sql_buffer.write("\t\tdiff_content text;\n")
        sql_buffer.write("\t\tdiff_output_file text;\n")
        sql_buffer.write("\t\tscript_code_escaped text;\n")
        sql_buffer.write("\t\tdb_code_escaped text;\n")
        sql_buffer.write(f"\t\tdiff_template_path text := '{input_output.diff_template_path}';\n")
        sql_buffer.write(f"\t\tdiff_output_dir text := basePath;\n")
        sql_buffer.write("\t\tdiff_rec RECORD;\n")
        sql_buffer.write("\tBEGIN\n")
        sql_buffer.write("\t\t-- Read the diff template file. Not when the caller is rendering: pg_read_file\n")
        sql_buffer.write("\t\t-- needs rights a managed server does not grant, and it would throw here and\n")
        sql_buffer.write("\t\t-- lose every diff before the loops had begun\n")
        sql_buffer.write("\t\tIF reportToCaller = False THEN\n")
        sql_buffer.write("\t\t\tSELECT pg_read_file(diff_template_path) INTO diff_template;\n")
        sql_buffer.write("\t\tEND IF;\n")
        sql_buffer.write("\t\t\n")
        # Only when coded entities are in scope: their state table (ScriptCode) exists only then
        if include_coded:
            sql_buffer.write("\t\t-- Loop through coded entities with differences\n")
            sql_buffer.write("\t\tFOR diff_rec IN \n")
            sql_buffer.write("\t\t\tSELECT \n")
            sql_buffer.write("\t\t\t\tsc.ent_schema,\n")
            sql_buffer.write("\t\t\t\tsc.ent_name,\n")
            sql_buffer.write("\t\t\t\tCOALESCE(sc.ent_type_pg, sc.ent_type) as ent_type,\n")
            sql_buffer.write("\t\t\t\tsc.param_type_list,\n")
            sql_buffer.write("\t\t\t\tsc.SQL_CREATE as script_code,\n")
            sql_buffer.write("\t\t\t\tdb_code.definition as db_code\n")
            sql_buffer.write("\t\t\tFROM ScriptCode sc\n")
            sql_buffer.write("\t\t\tINNER JOIN (\n")
            sql_buffer.write("\t\t\t\t-- Views\n")
            sql_buffer.write("\t\t\t\tSELECT v.table_schema as ent_schema, v.table_name as ent_name,\n")
            sql_buffer.write("\t\t\t\t\t'CREATE OR REPLACE VIEW ' || v.table_schema || '.' || v.table_name || E'\\nAS\\n' || v.view_definition AS definition,\n")
            sql_buffer.write("\t\t\t\t\t'' as param_type_list\n")
            sql_buffer.write("\t\t\t\tFROM information_schema.views v\n")
            sql_buffer.write("\t\t\t\tWHERE v.table_schema NOT IN ('information_schema', 'pg_catalog')\n")
            sql_buffer.write("\t\t\t\tUNION ALL\n")
            sql_buffer.write("\t\t\t\t-- Functions/Procedures\n")
            sql_buffer.write("\t\t\t\tSELECT n.nspname as ent_schema, p.proname as ent_name,\n")
            sql_buffer.write("\t\t\t\t\tCASE WHEN l.lanname = 'internal' THEN p.prosrc\n")
            sql_buffer.write("\t\t\t\t\t\tELSE pg_get_functiondef(p.oid)\n")
            sql_buffer.write("\t\t\t\t\tEND as definition,\n")
            sql_buffer.write("\t\t\t\t\tpg_get_function_arguments(p.oid) as param_type_list\n")
            sql_buffer.write("\t\t\t\tFROM pg_proc p\n")
            sql_buffer.write("\t\t\t\tLEFT JOIN pg_namespace n ON p.pronamespace = n.oid\n")
            sql_buffer.write("\t\t\t\tLEFT JOIN pg_language l ON p.prolang = l.oid\n")
            sql_buffer.write("\t\t\t\tWHERE n.nspname NOT IN ('pg_catalog', 'information_schema')\n")
            sql_buffer.write("\t\t\t\tUNION ALL\n")
            sql_buffer.write("\t\t\t\t-- Triggers\n")
            sql_buffer.write("\t\t\t\tSELECT n2.nspname as ent_schema, tg.tgname as ent_name,\n")
            sql_buffer.write("\t\t\t\t\tpg_get_triggerdef(tg.oid) as definition, '' as param_type_list\n")
            sql_buffer.write("\t\t\t\tFROM pg_trigger tg\n")
            sql_buffer.write("\t\t\t\tJOIN pg_class c2 ON c2.oid = tg.tgrelid\n")
            sql_buffer.write("\t\t\t\tJOIN pg_namespace n2 ON n2.oid = c2.relnamespace\n")
            sql_buffer.write("\t\t\t\tWHERE NOT tg.tgisinternal AND n2.nspname NOT IN ('pg_catalog', 'information_schema')\n")
            sql_buffer.write("\t\t\t) db_code ON LOWER(sc.ent_schema) = LOWER(db_code.ent_schema)\n")
            sql_buffer.write("\t\t\t\tAND LOWER(sc.ent_name) = LOWER(db_code.ent_name)\n")
            sql_buffer.write("\t\t\t\tAND LOWER(COALESCE(sc.param_type_list, '')) = LOWER(COALESCE(db_code.param_type_list, ''))\n")
            sql_buffer.write("\t\t\tWHERE sc.codeStat = 3\n")
            sql_buffer.write("\t\tLOOP\n")
            sql_buffer.write("\t\t\t-- Generate filename: diff_schema_name_paramhash.html\n")
            sql_buffer.write("\t\t\tdiff_output_file := diff_output_dir || '/diff_' || \n")
            sql_buffer.write("\t\t\t\treplace(diff_rec.ent_schema, '.', '_') || '_' || \n")
            sql_buffer.write("\t\t\t\treplace(diff_rec.ent_name, '.', '_');\n")
            sql_buffer.write("\t\t\t\n")
            sql_buffer.write("\t\t\t-- Add param hash if there are parameters (for overloaded functions)\n")
            sql_buffer.write("\t\t\tIF diff_rec.param_type_list IS NOT NULL AND diff_rec.param_type_list <> '' THEN\n")
            sql_buffer.write("\t\t\t\tdiff_output_file := diff_output_file || '_' || \n")
            sql_buffer.write("\t\t\t\t\tmd5(diff_rec.param_type_list);\n")
            sql_buffer.write("\t\t\tEND IF;\n")
            sql_buffer.write("\t\t\tdiff_output_file := diff_output_file || '.html';\n")
            sql_buffer.write("\t\t\t\n")
            # Hand the two sides back as data and let the caller render them. The escaping below is for
            # embedding in JavaScript, which is the renderer's business, so the raw text goes back instead
            sql_buffer.write("\t\t\tIF reportToCaller = True THEN\n")
            sql_buffer.write("\t\t\t\tINSERT INTO scriptreport (kind, name, ent_schema, ent_name, content)\n")
            sql_buffer.write("\t\t\t\tVALUES ('diff', regexp_replace(diff_output_file, '^.*/', ''),\n")
            sql_buffer.write("\t\t\t\t\tdiff_rec.ent_schema, diff_rec.ent_name,\n")
            sql_buffer.write("\t\t\t\t\tjson_build_object('entity_name', diff_rec.ent_name,\n")
            sql_buffer.write("\t\t\t\t\t\t'entity_schema', diff_rec.ent_schema,\n")
            sql_buffer.write("\t\t\t\t\t\t'entity_type', diff_rec.ent_type,\n")
            sql_buffer.write("\t\t\t\t\t\t'script_code', COALESCE(diff_rec.script_code, ''),\n")
            sql_buffer.write("\t\t\t\t\t\t'db_code', COALESCE(diff_rec.db_code, ''),\n")
            sql_buffer.write("\t\t\t\t\t\t'source_sql', '[]'::json, 'target_sql', '[]'::json)::text);\n")
            sql_buffer.write("\t\t\tELSE\n")
            sql_buffer.write("\t\t\t-- Escape code for JavaScript (handle quotes, newlines, backslashes)\n")
            sql_buffer.write("\t\t\tscript_code_escaped := replace(replace(replace(replace(\n")
            sql_buffer.write("\t\t\t\tCOALESCE(diff_rec.script_code, ''),\n")
            sql_buffer.write("\t\t\t\t'\\', '\\\\'),  -- escape backslashes first\n")
            sql_buffer.write("\t\t\t\t'''', '\\'''),  -- escape single quotes\n")
            sql_buffer.write("\t\t\t\tE'\\n', '\\n'),  -- preserve newlines for JS\n")
            sql_buffer.write("\t\t\t\tE'\\r', '\\r');  -- preserve carriage returns for JS\n")
            sql_buffer.write("\t\t\t\n")
            sql_buffer.write("\t\t\tdb_code_escaped := replace(replace(replace(replace(\n")
            sql_buffer.write("\t\t\t\tCOALESCE(diff_rec.db_code, ''),\n")
            sql_buffer.write("\t\t\t\t'\\', '\\\\'),\n")
            sql_buffer.write("\t\t\t\t'''', '\\'''),\n")
            sql_buffer.write("\t\t\t\tE'\\n', '\\n'),\n")
            sql_buffer.write("\t\t\t\tE'\\r', '\\r');\n")
            sql_buffer.write("\t\t\t\n")
            sql_buffer.write("\t\t\t-- Build the diff content by replacing placeholders\n")
            sql_buffer.write("\t\t\tdiff_content := diff_template;\n")
            sql_buffer.write("\t\t\tdiff_content := replace(diff_content, '[[ENTITY_NAME]]', diff_rec.ent_name);\n")
            sql_buffer.write("\t\t\tdiff_content := replace(diff_content, '[[ENTITY_SCHEMA]]', diff_rec.ent_schema);\n")
            sql_buffer.write("\t\t\tdiff_content := replace(diff_content, '[[ENTITY_TYPE]]', diff_rec.ent_type);\n")
            sql_buffer.write("\t\t\tdiff_content := replace(diff_content, '[[SCRIPT_CODE]]', '''' || script_code_escaped || '''');\n")
            sql_buffer.write("\t\t\tdiff_content := replace(diff_content, '[[DB_CODE]]', '''' || db_code_escaped || '''');\n")
            sql_buffer.write("\t\t\t--statement cards are for tables only\n")
            sql_buffer.write("\t\t\tdiff_content := replace(diff_content, '[[SOURCE_SQL]]', '[]');\n")
            sql_buffer.write("\t\t\tdiff_content := replace(diff_content, '[[TARGET_SQL]]', '[]');\n")
            sql_buffer.write(f"\t\t\tdiff_content := replace(diff_content, '[[leftPanelTitle]]', {left_title_sql});\n")
            sql_buffer.write(f"\t\t\tdiff_content := replace(diff_content, '[[rightPanelTitle]]', {right_title_sql});\n")
            sql_buffer.write(f"\t\t\tdiff_content := replace(diff_content, '[[generatedAt]]', {utils.PG_GENERATED_AT_EXPR});\n")
            sql_buffer.write(f"\t\t\tdiff_content := replace(diff_content, '[[version]]', '{__version__}');\n")
            sql_buffer.write("\t\t\t\n")
            sql_buffer.write("\t\t\t-- Write the diff file\n")
            sql_buffer.write("\t\t\tDROP TABLE IF EXISTS temp_diff_file;\n")
            sql_buffer.write("\t\t\tCREATE TEMP TABLE temp_diff_file (content text);\n")
            sql_buffer.write("\t\t\tINSERT INTO temp_diff_file VALUES (diff_content);\n")
            sql_buffer.write("\t\t\tEXECUTE format('COPY temp_diff_file TO %L WITH (FORMAT CSV, QUOTE E''\\x01'', DELIMITER E''\\x02'')', diff_output_file);\n")
            sql_buffer.write("\t\t\tDROP TABLE temp_diff_file;\n")
            sql_buffer.write("\t\t\t\n")
            sql_buffer.write("\t\t\tRAISE NOTICE 'Created diff file: %', diff_output_file;\n")
            sql_buffer.write("\t\t\tEND IF; --reportToCaller\n")
            sql_buffer.write("\t\tEND LOOP;\n")
            sql_buffer.write("\t\t\n")
        generate_source_sql_for_tables(sql_buffer)
        sql_buffer.write("\t\t-- Loop through tables with differences\n")
        sql_buffer.write("\t\tFOR diff_rec IN \n")
        sql_buffer.write("\t\t\tSELECT \n")
        sql_buffer.write("\t\t\t\tst.table_schema,\n")
        sql_buffer.write("\t\t\t\tst.table_name,\n")
        sql_buffer.write("\t\t\t\t'Table' as ent_type,\n")
        sql_buffer.write("\t\t\t\t-- Script version: use the full SQL_CREATE from ScriptTables\n")
        sql_buffer.write("\t\t\t\tst.SQL_CREATE as script_code,\n")
        sql_buffer.write("\t\t\t\t-- DB version: build full CREATE TABLE from system catalogs\n")
        sql_buffer.write("\t\t\t\t(\n")
        sql_buffer.write("\t\t\t\t\t-- CREATE TABLE header\n")
        sql_buffer.write("\t\t\t\t\t'CREATE TABLE ' || st.table_schema || '.' || st.table_name || E'\\n(' || E'\\n' ||\n")
        sql_buffer.write("\t\t\t\t\t-- Columns\n")
        sql_buffer.write("\t\t\t\t\t(SELECT string_agg(\n")
        # An integer column defaulting to nextval() is shown as serial/bigserial/smallserial, without the DEFAULT -
        # the same rule the script side uses (_is_serial_default), so an identical column doesn't show as different
        serial_type = ("CASE WHEN c.column_default ILIKE 'nextval(%' THEN "
                       "CASE c.udt_name WHEN 'int4' THEN 'serial' WHEN 'int8' THEN 'bigserial' WHEN 'int2' THEN 'smallserial' END END")
        sql_buffer.write(f"\t\t\t\t\t\tc.column_name || ' ' || COALESCE({serial_type}, c.udt_name) || \n")
        sql_buffer.write("\t\t\t\t\t\tCASE WHEN c.character_maximum_length IS NOT NULL THEN '(' || c.character_maximum_length || ')' ELSE '' END ||\n")
        # numeric(p,s) as the script side shows it (add_size_precision_scale); unconstrained numeric has no precision
        sql_buffer.write("\t\t\t\t\t\tCASE WHEN c.udt_name = 'numeric' AND c.numeric_precision IS NOT NULL THEN '(' || c.numeric_precision || ',' || c.numeric_scale || ')' ELSE '' END ||\n")
        sql_buffer.write("\t\t\t\t\t\tCASE WHEN c.is_nullable = 'YES' THEN ' NULL' ELSE ' NOT NULL' END ||\n")
        sql_buffer.write("\t\t\t\t\t\tCASE WHEN c.is_identity = 'YES' THEN ' GENERATED ' || c.identity_generation || ' AS IDENTITY' ELSE '' END ||\n")
        sql_buffer.write(f"\t\t\t\t\t\tCASE WHEN c.column_default IS NOT NULL AND c.is_identity = 'NO' AND {serial_type} IS NULL THEN ' DEFAULT ' || c.column_default ELSE '' END,\n")
        sql_buffer.write("\t\t\t\t\t\tE',\\n' ORDER BY c.ordinal_position)\n")
        sql_buffer.write("\t\t\t\t\t FROM information_schema.columns c \n")
        sql_buffer.write("\t\t\t\t\t WHERE c.table_schema = st.table_schema AND c.table_name = st.table_name\n")
        sql_buffer.write("\t\t\t\t\t) || E'\\n);' ||\n")
        sql_buffer.write("\t\t\t\t\t-- Primary Key\n")
        sql_buffer.write("\t\t\t\t\tCOALESCE((\n")
        sql_buffer.write("\t\t\t\t\t\tSELECT E'\\nALTER TABLE ' || st.table_schema || '.' || st.table_name || \n")
        sql_buffer.write("\t\t\t\t\t\t\t' ADD CONSTRAINT ' || tc.constraint_name || ' PRIMARY KEY (' ||\n")
        sql_buffer.write("\t\t\t\t\t\t\tstring_agg(kcu.column_name, ', ' ORDER BY kcu.ordinal_position) || ');'\n")
        sql_buffer.write("\t\t\t\t\t\tFROM information_schema.table_constraints tc\n")
        sql_buffer.write("\t\t\t\t\t\tJOIN information_schema.key_column_usage kcu \n")
        sql_buffer.write("\t\t\t\t\t\t\tON tc.constraint_name = kcu.constraint_name AND tc.table_schema = kcu.table_schema\n")
        sql_buffer.write("\t\t\t\t\t\tWHERE tc.table_schema = st.table_schema AND tc.table_name = st.table_name\n")
        sql_buffer.write("\t\t\t\t\t\t\tAND tc.constraint_type = 'PRIMARY KEY'\n")
        sql_buffer.write("\t\t\t\t\t\tGROUP BY tc.constraint_name\n")
        sql_buffer.write("\t\t\t\t\t), '') ||\n")
        sql_buffer.write("\t\t\t\t\t-- Indexes (non-primary key, non-unique constraint)\n")
        sql_buffer.write("\t\t\t\t\tCOALESCE((\n")
        sql_buffer.write("\t\t\t\t\t\tSELECT string_agg(E'\\n' || indexdef || ';', '')\n")
        sql_buffer.write("\t\t\t\t\t\tFROM pg_indexes pi\n")
        sql_buffer.write("\t\t\t\t\t\tWHERE pi.schemaname = st.table_schema AND pi.tablename = st.table_name\n")
        sql_buffer.write("\t\t\t\t\t\t\tAND pi.indexname NOT IN (\n")
        sql_buffer.write("\t\t\t\t\t\t\t\tSELECT tc.constraint_name FROM information_schema.table_constraints tc\n")
        sql_buffer.write("\t\t\t\t\t\t\t\tWHERE tc.table_schema = st.table_schema AND tc.table_name = st.table_name\n")
        sql_buffer.write("\t\t\t\t\t\t\t\t\tAND tc.constraint_type IN ('PRIMARY KEY', 'UNIQUE')\n")
        sql_buffer.write("\t\t\t\t\t\t\t)\n")
        sql_buffer.write("\t\t\t\t\t), '') ||\n")
        sql_buffer.write("\t\t\t\t\t-- Foreign Keys\n")
        sql_buffer.write("\t\t\t\t\tCOALESCE((\n")
        sql_buffer.write("\t\t\t\t\t\tSELECT string_agg(\n")
        sql_buffer.write("\t\t\t\t\t\t\tE'\\nALTER TABLE ' || tc.table_schema || '.' || tc.table_name ||\n")
        sql_buffer.write("\t\t\t\t\t\t\t' ADD CONSTRAINT ' || tc.constraint_name || ' FOREIGN KEY (' ||\n")
        sql_buffer.write("\t\t\t\t\t\t\t(SELECT string_agg(kcu.column_name, ', ' ORDER BY kcu.ordinal_position)\n")
        sql_buffer.write("\t\t\t\t\t\t\t FROM information_schema.key_column_usage kcu\n")
        sql_buffer.write("\t\t\t\t\t\t\t WHERE kcu.constraint_name = tc.constraint_name AND kcu.table_schema = tc.table_schema) ||\n")
        sql_buffer.write("\t\t\t\t\t\t\t') REFERENCES ' ||\n")
        sql_buffer.write("\t\t\t\t\t\t\t(SELECT ccu.table_schema || '.' || ccu.table_name || '(' ||\n")
        sql_buffer.write("\t\t\t\t\t\t\t\tstring_agg(ccu.column_name, ', ') || ')'\n")
        sql_buffer.write("\t\t\t\t\t\t\t FROM information_schema.constraint_column_usage ccu\n")
        sql_buffer.write("\t\t\t\t\t\t\t WHERE ccu.constraint_name = tc.constraint_name AND ccu.table_schema = tc.table_schema\n")
        sql_buffer.write("\t\t\t\t\t\t\t GROUP BY ccu.table_schema, ccu.table_name) || ';',\n")
        sql_buffer.write("\t\t\t\t\t\t\t'')\n")
        sql_buffer.write("\t\t\t\t\t\tFROM information_schema.table_constraints tc\n")
        sql_buffer.write("\t\t\t\t\t\tWHERE tc.table_schema = st.table_schema AND tc.table_name = st.table_name\n")
        sql_buffer.write("\t\t\t\t\t\t\tAND tc.constraint_type = 'FOREIGN KEY'\n")
        sql_buffer.write("\t\t\t\t\t), '')\n")
        sql_buffer.write("\t\t\t\t) as db_code,\n")
        sql_buffer.write("\t\t\t\tst.tablestat,\n")
        # Statements to run on the target: what the script generated for the table, in execution order. Extra tables
        # are dropped after this runs, so their DROP TABLE isn't in scriptoutput yet and is added here directly
        if drops_extra_tables:
            sql_buffer.write("\t\t\t\tCOALESCE(tsql.statements, CASE WHEN st.tablestat = 2 THEN json_build_array('DROP TABLE ' || st.table_schema || '.' || st.table_name) END) as target_sql,\n")
        else:
            sql_buffer.write("\t\t\t\ttsql.statements as target_sql,\n")
        sql_buffer.write("\t\t\t\tssql.statements as source_sql\n")
        sql_buffer.write("\t\t\tFROM ScriptTables st\n")
        sql_buffer.write("\t\t\tLEFT JOIN (\n")
        sql_buffer.write("\t\t\t\tSELECT LOWER(ent_schema) AS ent_schema, LOWER(ent_name) AS ent_name, json_agg(sql_text ORDER BY ord, sub_ord) AS statements\n")
        sql_buffer.write("\t\t\t\tFROM tmp_source_sql\n")
        sql_buffer.write("\t\t\t\tGROUP BY LOWER(ent_schema), LOWER(ent_name)\n")
        sql_buffer.write("\t\t\t) ssql ON ssql.ent_schema = LOWER(st.table_schema) AND ssql.ent_name = LOWER(st.table_name)\n")
        # Aggregate once (not per table): scriptoutput can hold many data statements
        sql_buffer.write("\t\t\tLEFT JOIN (\n")
        # Terminated the same way as the returned statements, so the report and the output agree
        sql_buffer.write("\t\t\t\tSELECT LOWER(SO.ent_schema) AS ent_schema, LOWER(SO.ent_name) AS ent_name, "
                         f"json_agg({utils.pg_terminated_statement('SO.SQLText')} ORDER BY SO.id) AS statements\n")
        sql_buffer.write("\t\t\t\tFROM scriptoutput SO\n")
        sql_buffer.write("\t\t\t\tWHERE SO.ent_schema IS NOT NULL\n")
        sql_buffer.write("\t\t\t\tGROUP BY LOWER(SO.ent_schema), LOWER(SO.ent_name)\n")
        sql_buffer.write("\t\t\t) tsql ON tsql.ent_schema = LOWER(st.table_schema) AND tsql.ent_name = LOWER(st.table_name)\n")
        sql_buffer.write("\t\t\tWHERE st.tablestat IN (1, 2, 3) --different, or on one side only (one side of the comparison is then empty)\n")
        sql_buffer.write("\t\tLOOP\n")
        sql_buffer.write("\t\t\t-- Generate filename: diff_table_schema_name.html\n")
        sql_buffer.write("\t\t\tdiff_output_file := diff_output_dir || '/diff_table_' || \n")
        sql_buffer.write("\t\t\t\treplace(diff_rec.table_schema, '.', '_') || '_' || \n")
        sql_buffer.write("\t\t\t\treplace(diff_rec.table_name, '.', '_') || '.html';\n")
        sql_buffer.write("\t\t\t\n")
        sql_buffer.write("\t\t\t-- Escape code for JavaScript\n")
        sql_buffer.write("\t\t\tscript_code_escaped := replace(replace(replace(replace(\n")
        sql_buffer.write("\t\t\t\tCOALESCE(diff_rec.script_code, ''),\n")
        sql_buffer.write("\t\t\t\t'\\', '\\\\'),\n")
        sql_buffer.write("\t\t\t\t'''', '\\'''),\n")
        sql_buffer.write("\t\t\t\tE'\\n', '\\n'),\n")
        sql_buffer.write("\t\t\t\tE'\\r', '\\r');\n")
        sql_buffer.write("\t\t\t\n")
        sql_buffer.write("\t\t\tdb_code_escaped := replace(replace(replace(replace(\n")
        sql_buffer.write("\t\t\t\tCOALESCE(diff_rec.db_code, ''),\n")
        sql_buffer.write("\t\t\t\t'\\', '\\\\'),\n")
        sql_buffer.write("\t\t\t\t'''', '\\'''),\n")
        sql_buffer.write("\t\t\t\tE'\\n', '\\n'),\n")
        sql_buffer.write("\t\t\t\tE'\\r', '\\r');\n")
        sql_buffer.write("\t\t\t\n")
        sql_buffer.write("\t\t\t-- Build the diff content\n")
        # As above: the data goes back, the rendering happens where the files can actually be written. The
        # two SQL arrays are built the same way, since they are the comparison rather than presentation
        sql_buffer.write("\t\t\tIF reportToCaller = True THEN\n")
        sql_buffer.write("\t\t\t\tINSERT INTO scriptreport (kind, name, ent_schema, ent_name, content)\n")
        sql_buffer.write("\t\t\t\tVALUES ('diff', regexp_replace(diff_output_file, '^.*/', ''),\n")
        sql_buffer.write("\t\t\t\t\tdiff_rec.table_schema, diff_rec.table_name,\n")
        sql_buffer.write("\t\t\t\t\tjson_build_object('entity_name', diff_rec.table_name,\n")
        sql_buffer.write("\t\t\t\t\t\t'entity_schema', diff_rec.table_schema,\n")
        sql_buffer.write("\t\t\t\t\t\t'entity_type', diff_rec.ent_type,\n")
        sql_buffer.write("\t\t\t\t\t\t'script_code', COALESCE(diff_rec.script_code, ''),\n")
        sql_buffer.write("\t\t\t\t\t\t'db_code', COALESCE(diff_rec.db_code, ''),\n")
        sql_buffer.write("\t\t\t\t\t\t'source_sql', COALESCE((CASE diff_rec.tablestat\n")
        sql_buffer.write("\t\t\t\t\t\t\tWHEN 1 THEN json_build_array('DROP TABLE ' || diff_rec.table_schema || '.' || diff_rec.table_name || ';')\n")
        sql_buffer.write("\t\t\t\t\t\t\tWHEN 2 THEN json_build_array(diff_rec.db_code)\n")
        sql_buffer.write("\t\t\t\t\t\t\tELSE diff_rec.source_sql END), '[]'::json),\n")
        sql_buffer.write("\t\t\t\t\t\t'target_sql', COALESCE(diff_rec.target_sql, '[]'::json))::text);\n")
        sql_buffer.write("\t\t\tELSE\n")
        sql_buffer.write("\t\t\tdiff_content := diff_template;\n")
        sql_buffer.write("\t\t\tdiff_content := replace(diff_content, '[[ENTITY_NAME]]', diff_rec.table_name);\n")
        sql_buffer.write("\t\t\tdiff_content := replace(diff_content, '[[ENTITY_SCHEMA]]', diff_rec.table_schema);\n")
        sql_buffer.write("\t\t\tdiff_content := replace(diff_content, '[[ENTITY_TYPE]]', diff_rec.ent_type);\n")
        sql_buffer.write("\t\t\tdiff_content := replace(diff_content, '[[SCRIPT_CODE]]', '''' || script_code_escaped || '''');\n")
        sql_buffer.write("\t\t\tdiff_content := replace(diff_content, '[[DB_CODE]]', '''' || db_code_escaped || '''');\n")
        sql_buffer.write("\t\t\t-- JSON arrays of statements, inside a <script> block: escape '</' so SQL containing '</script>' can't close it.\n")
        sql_buffer.write("\t\t\t-- Source side: a table only in the script is dropped; a table only in this database is created as it is here\n")
        sql_buffer.write("\t\t\tdiff_content := replace(diff_content, '[[SOURCE_SQL]]', replace(COALESCE((CASE diff_rec.tablestat\n")
        sql_buffer.write("\t\t\t\tWHEN 1 THEN json_build_array('DROP TABLE ' || diff_rec.table_schema || '.' || diff_rec.table_name || ';')\n")
        sql_buffer.write("\t\t\t\tWHEN 2 THEN json_build_array(diff_rec.db_code)\n")
        sql_buffer.write("\t\t\t\tELSE diff_rec.source_sql END)::text, '[]'), '</', '<\\/'));\n")
        sql_buffer.write("\t\t\tdiff_content := replace(diff_content, '[[TARGET_SQL]]', replace(COALESCE(diff_rec.target_sql::text, '[]'), '</', '<\\/'));\n")
        sql_buffer.write(f"\t\t\tdiff_content := replace(diff_content, '[[leftPanelTitle]]', {left_title_sql});\n")
